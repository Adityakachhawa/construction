// Uses an existing Playwright installation; no project dependency is added.
// Usage: node scripts/production-preflight.mjs <playwright index> <chromium executable>
import { pathToFileURL } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';
import assert from 'node:assert/strict';
const { chromium } = await import(pathToFileURL(process.argv[2]).href);
const root=path.resolve('dist');
const server=http.createServer((req,res)=>{
 let name=decodeURIComponent(new URL(req.url,'http://localhost').pathname);
 if(name.endsWith('/')) name+='index.html';
 const file=path.resolve(root,'.'+name);
 if(!file.startsWith(root+path.sep)||!fs.existsSync(file)){res.writeHead(404);res.end();return;}
 const mime={'.js':'text/javascript','.css':'text/css','.html':'text/html','.svg':'image/svg+xml','.json':'application/json'};
 res.setHeader('Content-Type',mime[path.extname(file)]??'application/octet-stream');res.end(fs.readFileSync(file));
});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const base=`http://127.0.0.1:${server.address().port}`;
const browser=await chromium.launch({headless:true,...(process.argv[3]?{executablePath:process.argv[3]}:{})});
const errors=[];let checks=0;
const product={mortar_mode:'coverage',mortar_bag_mass:25,mortar_bag_unit:'kg',mortar_block_length:390,mortar_block_height:190,mortar_block_width:190,mortar_joint:10,mortar_bedding:'face-shell',mortar_blocks_per_bag:20,mortar_waste_pct:0};
const block={...product,length_ft:16,height_ft:8,length_m:4,height_m:2,waste_pct:0};
const cases=[
 ['flooring-calculator',{length_ft:10,width_ft:10,length_m:10,width_m:10,box_coverage:20,box_coverage_m2:20,waste_pct:10},{area_with_waste:110,boxes:6}],
 ['plywood-calculator',{length_ft:8,width_ft:4,length_m:2.4384,width_m:1.2192,sheet_size:'4x8',waste_pct:0},{sheets_net:1,sheets_waste:1}],
 ['concrete-block-calculator',block,{blocks:144,mortar_bags:8},{blocks:100,mortar_bags:5}],
 ['mortar-calculator',{length_ft:10,height_ft:10,length_m:3.048,height_m:3.048,unit_type:'custom',custom_joint_factor:0.03,bag_size:'custom',custom_yield:0.5,waste_pct:0},{mortar_cuft:3,bags_required:6}],
 ['grout-calculator',{area_sqft:100,area_sqm:9.290304,tile_length_in:12,tile_width_in:12,joint_width_in:0.125,tile_depth_in:0.25,tile_length_mm:304.8,tile_width_mm:304.8,joint_width_mm:3.175,tile_depth_mm:6.35,waste_pct:0},{grout_cuft:0.043,net_bags:1}],
 ['concrete-block-calculator/8x20',block,{blocks:144,mortar_bags:8},{blocks:100,mortar_bags:5}]
];
try{
 const context=await browser.newContext();await context.addInitScript(()=>Object.defineProperty(navigator,'clipboard',{value:{writeText:async text=>{window.copiedText=text;}}}));
 const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.url().startsWith(base)&&r.status()>=400)errors.push(r.status()+' '+r.url());});
 const ready=()=>page.locator('#calc-form [aria-invalid]').first().waitFor({state:'attached'});
 const verify=async(expected)=>{for(const [id,value] of Object.entries(expected))assert.equal(await page.locator(`[data-output-id="${id}"] .result-primary-number, [data-output-id="${id}"] .result-secondary-number`).innerText(),String(value),id);};
 const sitemap=fs.readFileSync('dist/sitemap.xml','utf8');
 for(const [slug,inputs,imperial,metric=imperial] of cases){
  const route='/calculators/'+slug+'/';const canonical='https://buildbymath.com'+route;
  assert.ok(sitemap.includes('<loc>'+canonical+'</loc>'),slug+' sitemap');
  for(const unit of ['imperial','metric']){
   const expected=unit==='imperial'?imperial:metric;
   const response=await page.goto(base+route+'?'+new URLSearchParams({...inputs,unit}));assert.equal(response.status(),200);await ready();
   assert.equal(await page.locator('link[rel=canonical]').getAttribute('href'),canonical);await verify(expected);
   await page.locator('#action-copy-results').click();const copied=await page.evaluate(()=>window.copiedText);assert.ok(copied.includes('Generated by BuildByMath'));for(const value of Object.values(expected))assert.ok(copied.includes(': '+value.toLocaleString('en-US',{maximumFractionDigits:2})),slug+' copied quantity');
   await page.locator('#action-share').click();const shared=await page.evaluate(()=>window.copiedText);assert.equal(new URL(shared).searchParams.get('unit'),unit);
   await page.goto(shared);await ready();await verify(expected);checks++;
  }
  console.log('PASS '+slug+': both units, results, copy, share, canonical, sitemap');
 }
 await page.goto(base+'/calculators/concrete-block-calculator/8x20/');await ready();assert.equal(await page.locator('#primary-value').innerText(),'189');assert.match(await page.locator('[data-output-id=mortar_bags] .result-secondary-number').innerText(),/Requires product specifications/);checks++;
 assert.deepEqual(errors,[]);console.log(JSON.stringify({productionChecks:checks,failures:0,runtimeOrResourceErrors:errors}));
}finally{await browser.close();await new Promise(r=>server.close(r));}
